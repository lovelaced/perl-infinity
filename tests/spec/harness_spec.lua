    local w = h.world
    for _ = 1, steps do
      local r = rnd(10)
      if r == 1 then w:combat(not w.inCombat)
      elseif r == 2 then w:setTarget(rnd(2) == 1 and { name = "Mob", npc = true, reaction = 2 } or nil)
      elseif r == 3 then w:damage("player", rnd(100))
      elseif r == 4 then w:heal("player", rnd(100))
      elseif r == 5 and not w.inCombat then w:setParty(rnd(2) == 1 and { {}, {} } or {})
      elseif r == 6 and w:get("target") then w:damage("target", rnd(50))
      elseif r == 7 then w:instance(rnd(2) == 1 and "party" or "none")
      elseif r == 8 then w:applyAura("player", { name = "Buff", duration = 10 })
      else h:advance(0.1) end
    end
    w:combat(false)
  end)
end)

