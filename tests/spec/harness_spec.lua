-- tests/spec/harness_spec.lua
-- Self-tests for the offline harness, using tests/fixtures/FixtureAddon so the
-- harness is proven before the real addon exists.

local FIXTURE = ROOT .. "/tests/fixtures/FixtureAddon/FixtureAddon.toc"

local function boot(mode, sv)
  local h = Harness.new({ mode = mode })
  h:loadToc(FIXTURE)
  h:login(sv)
  return h, h.addon.ns
end

describe("secret values", function()
  it("errors on arithmetic, comparison, indexing, length and calls", function()
    local h = Harness.new({ mode = "strict" })
    local hp = h.env.UnitHealth("player")
    expect(hp).toBeSecret()
    expect(function() return hp + 1 end).toThrow("arithmetic")
    expect(function() return -hp end).toThrow("arithmetic")
    expect(function() return hp < 5 end).toThrow("compare")
    expect(function() return hp == h.env.UnitHealth("player") end).toThrow("compare")
    expect(function() return hp.x end).toThrow("index")
    expect(function() return #hp end).toThrow("length")
    expect(function() return hp() end).toThrow("call")
    expect(function() return h.env.tonumber(hp) end).toThrow("tonumber")
  end)

  it("treats a secret as non-nil and different-type equality as plain false", function()
    local h = Harness.new({ mode = "strict" })
    local hp = h.env.UnitHealth("player")
    expect(hp ~= nil).toBe(true)
    expect(hp == 5).toBe(false)
  end)

  it("concatenation, tostring and format produce secret strings", function()
    local h = Harness.new({ mode = "strict" })
    local env = h.env
    local hp = env.UnitHealth("player")
    expect("HP " .. hp).toBeRaw("HP 4000")
    expect(env.tostring(hp)).toBeRaw("4000")
    expect(env.format("%d/%d", hp, 10)).toBeRaw("4000/10")
    expect(("%d%%"):format(hp)).toBeRaw("4000%")
    expect(env.type(hp)).toBe("number")
    local name = env.UnitName("player")
    expect(function() return env.format("%.3s", name) end).toThrow("precision")
  end)

  it("secret helpers and scrubbing", function()
    local h = Harness.new({ mode = "strict" })
    local env = h.env
    local hp = env.UnitHealth("player")
    expect(env.issecretvalue(hp)).toBe(true)
    expect(env.canaccessvalue(hp)).toBe(false)
    expect(env.canaccessallvalues(1, hp)).toBe(false)
    expect(env.scrubsecretvalues(hp)).toBeNil()
    expect(env.issecretvalue(env.secretwrap(3))).toBe(true)
  end)
end)

